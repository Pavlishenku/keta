#!/usr/bin/env python3
"""Generates the typing stubs of the keta Python package from the built module.

The extension `keta._keta` is compiled (pybind11): editors and type checkers
cannot read it. This tool imports it, reads the signature pybind11 writes on the
first line(s) of every docstring, and writes

  python/keta/_keta.pyi    every class, method, property and function, with its
                           parameters, return type and docstring;
  python/keta/__init__.pyi re-export of the whole extension (`import keta as k`
                           then sees every name, also those __init__.py adds
                           dynamically);
  python/keta/py.typed     the PEP 561 marker.

Usage:
  python3 tools/gen_pyi.py [--module build/python]          # (re)write the stubs
  python3 tools/gen_pyi.py [--module build/python] --check  # exit 1 if they drifted

Run it after every change of the bindings (src/keta/py/*); --check reports
stubs that no longer match the module.
"""

from __future__ import annotations

import argparse
import ast
import importlib
import inspect
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "python", "keta")
MOD = "keta._keta"

HEADER = (
    "# Generated by tools/gen_pyi.py from the compiled keta._keta module: do not edit by hand.\n"
    "# Regenerate after changing the bindings (src/keta/py/*):  python3 tools/gen_pyi.py\n"
)


def strip_annotated(t: str) -> str:
    """Annotated[X, FixedSize(n)] -> X (bracket-aware, repeated)."""
    while True:
        i = t.find("Annotated[")
        if i < 0:
            return t
        j, depth, comma = i + len("Annotated["), 1, -1
        k = j
        while k < len(t) and depth:
            c = t[k]
            if c == "[":
                depth += 1
            elif c == "]":
                depth -= 1
            elif c == "," and depth == 1 and comma < 0:
                comma = k
            k += 1
        inner = t[j:comma] if comma > 0 else t[j:k - 1]
        t = t[:i] + inner + t[k:]


def cpp_class_names() -> dict[str, str]:
    """C++ binding struct -> Python class name, read from the binding sources
    (py::class_<PyX>(mod, "Name") ...): a method declared before its result
    class is registered shows the C++ name in its pybind11 signature."""
    out = {}
    src = os.path.join(ROOT, "src", "keta", "py")
    for fn in sorted(os.listdir(src)):
        if fn.endswith((".cpp", ".inl")):
            text = open(os.path.join(src, fn), encoding="utf-8").read()
            for cpp, py in re.findall(r'py::class_<\s*(\w+)[^>]*>\s*\w*\s*\(\s*\w+\s*,\s*"(\w+)"', text):
                out[cpp] = py
    return out


CPP_NAMES = cpp_class_names()
LEAKS: set[str] = set()


def clean_type(t: str) -> str:
    t = t.strip()
    t = t.replace("keta._keta.", "")

    def cpp(mt: re.Match) -> str:
        name = mt.group(1)
        if name in CPP_NAMES:
            return CPP_NAMES[name]
        LEAKS.add(mt.group(0))
        return "Any"

    t = re.sub(r"(?:\(anonymous namespace\)|[A-Za-z_]\w*)(?:::[A-Za-z_]\w*)*::([A-Za-z_]\w*)", cpp, t)
    t = strip_annotated(t)
    t = re.sub(r"\btyping\.", "", t)
    t = re.sub(r"\bnumpy\.ndarray\b", "Any", t)
    if t in ("", "handle", "object"):
        return "Any" if t != "object" else "object"
    return t


def split_params(s: str) -> list[str]:
    """Split a parameter list on top-level commas (brackets, quotes respected)."""
    out, depth, cur, quote = [], 0, "", None
    for c in s:
        if quote:
            cur += c
            if c == quote:
                quote = None
            continue
        if c in "'\"":
            quote = c
        elif c in "[(<{":
            depth += 1
        elif c in "])>}":
            depth -= 1
        if c == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def find_close(s: str, i: int) -> int:
    """Index of the parenthesis closing the one at s[i]."""
    depth = 0
    quote = None
    for k in range(i, len(s)):
        c = s[k]
        if quote:
            if c == quote:
                quote = None
            continue
        if c in "'\"":
            quote = c
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return k
    raise ValueError(f"unbalanced signature: {s}")


def parse_sig(line: str, name: str):
    """'name(a: int, b: float = 1.0) -> str' -> (params, ret)."""
    i = line.index("(")
    j = find_close(line, i)
    params = []
    for p in split_params(line[i + 1:j]):
        if p in ("*", "/") or p.startswith("*"):
            params.append(p if p in ("*", "/") else p.split(":")[0].strip())
            continue
        default = None
        if "=" in p:
            # the default follows the last top-level '=' of the annotation
            head, default = p.split("=", 1)
            p = head.strip()
        if ":" in p:
            pname, ptype = p.split(":", 1)
            pname, ptype = pname.strip(), clean_type(ptype)
        else:
            pname, ptype = p.strip(), None
        params.append((pname, ptype, default is not None))
    rest = line[j + 1:].strip()
    ret = clean_type(rest[2:]) if rest.startswith("->") else "Any"
    return params, ret


def signatures(doc: str, name: str) -> tuple[list[str], str]:
    """The signature line(s) of a pybind11 docstring and the remaining text."""
    if not doc:
        return [], ""
    lines = doc.split("\n")
    if len(lines) > 1 and lines[1].strip() == "Overloaded function.":
        sigs, body = [], []
        for ln in lines[2:]:
            m = re.match(r"^\d+\. (" + re.escape(name) + r"\(.*)$", ln)
            if m:
                sigs.append(m.group(1))
            elif ln.strip():
                body.append(ln.strip())
        return sigs, "\n".join(dict.fromkeys(body))
    first = lines[0]
    if first.startswith(name + "(") or first.startswith("("):
        return [first if first.startswith(name) else name + first], "\n".join(lines[1:]).strip()
    return [], doc.strip()


def fmt_doc(text: str, indent: str) -> str:
    if not text:
        return ""
    t = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if "\n" in t:
        body = "\n".join((indent + ln) if ln.strip() else "" for ln in t.split("\n"))
        return f'{indent}"""\n{body}\n{indent}"""\n'
    return f'{indent}"""{t}"""\n'


def render_def(name: str, sig: str, doc: str, indent: str, method: bool, static: bool, overload: bool) -> str:
    params, ret = parse_sig(sig, name)
    out = []
    # pybind11 accepts a required parameter after a defaulted one (it can then
    # only be omitted-before by keyword); Python syntax cannot: such trailing
    # required parameters are written with a default too (permissive stub).
    seen_default = False
    for p in params:
        if isinstance(p, str):
            out.append(p)
            if p == "*":
                seen_default = False
            continue
        pname, ptype, has_default = p
        if has_default:
            seen_default = True
        elif seen_default:
            has_default = True
        if method and not static and pname == "self":
            out.append("self")
            continue
        if ptype:
            # pybind11's list / array casters take any sequence (tuple, list of
            # ints ...): parameters are typed with the covariant Sequence
            ptype = re.sub(r"\blist\[", "Sequence[", ptype)
        s = pname + (f": {ptype}" if ptype else "")
        if has_default:
            s += " = ..."
        out.append(s)
    if method and not static and (not out or out[0] != "self"):
        out.insert(0, "self")
    head = ""
    if overload:
        head += f"{indent}@overload\n"
    if static:
        head += f"{indent}@staticmethod\n"
    body = fmt_doc(doc, indent + "    ")
    if ret == "None" and name == "__init__":
        ret = "None"
    line = f"{indent}def {name}({', '.join(out)}) -> {ret}:"
    return head + (line + "\n" + body + f"{indent}    ...\n" if body else line + " ...\n")


def render_callable(name, obj, indent, method, static):
    sigs, doc = signatures(obj.__doc__ or "", name)
    if not sigs:
        args = "self, *args: Any, **kwargs: Any" if method and not static else "*args: Any, **kwargs: Any"
        return (f"{indent}@staticmethod\n" if static else "") + f"{indent}def {name}({args}) -> Any: ...\n"
    over = len(sigs) > 1
    return "".join(render_def(name, s, doc if k == 0 else "", indent, method, static, over) for k, s in enumerate(sigs))


def render_class(name: str, cls: type) -> str:
    out = [f"class {name}:\n"]
    doc = (cls.__doc__ or "").strip()
    if doc:
        out.append(fmt_doc(doc, "    "))
    members = []
    for attr, val in cls.__dict__.items():
        if attr.startswith("__") and attr not in ("__init__", "__repr__", "__len__", "__iter__", "__getitem__",
                                                    "__eq__", "__hash__", "__call__", "__contains__"):
            continue
        if attr.startswith("_") and not attr.startswith("__"):
            continue
        members.append((attr, val))
    for attr, val in members:
        if isinstance(val, property):
            fdoc = (val.fget.__doc__ or "") if val.fget else ""
            ret = "Any"
            first = fdoc.split("\n")[0]
            if "->" in first:
                ret = clean_type(first.split("->", 1)[1])
            rest = "\n".join(fdoc.split("\n")[1:]).strip()
            out.append("    @property\n")
            out.append(f"    def {attr}(self) -> {ret}:" + ("\n" + fmt_doc(rest, "        ") + "        ...\n" if rest
                                                            else " ...\n"))
        elif isinstance(val, staticmethod):
            out.append(render_callable(attr, val.__func__, "    ", True, True))
        elif callable(val):
            # dunders without a pybind11 signature are object's own (an
            # inherited __init__ of a class Python cannot construct): skipped
            if attr.startswith("__") and not signatures(val.__doc__ or "", attr)[0]:
                continue
            out.append(render_callable(attr, val, "    ", True, False))
    if len(out) == 1 or (len(out) == 2 and doc):
        out.append("    ...\n")
    return "".join(out)


def generate(module_path: str | None) -> dict[str, str]:
    if module_path:
        sys.path.insert(0, os.path.abspath(module_path))
    m = importlib.import_module(MOD)
    classes, funcs, consts = [], [], []
    for name in sorted(dir(m)):
        if name.startswith("_") and name != "__version__":
            continue
        obj = getattr(m, name)
        if inspect.isclass(obj):
            classes.append(name)
        elif callable(obj):
            funcs.append(name)
        elif name != "__version__" and isinstance(obj, (bool, int, float, str)):
            consts.append(name)  # module constants (e.g. SETRA_LOCK_IN_ACCEL)
    parts = [HEADER, "from typing import Any, Callable, Optional, Sequence, overload\n\n",
             f"__version__: str\n"]
    parts += [f"{c}: {type(getattr(m, c)).__name__}\n" for c in consts]
    parts.append("\n")
    for c in classes:
        parts.append(render_class(c, getattr(m, c)) + "\n")
    for f in funcs:
        parts.append(render_callable(f, getattr(m, f), "", False, False) + "\n")
    stub = "".join(parts).rstrip() + "\n"
    if LEAKS:
        print("warning: C++ types without a Python class, typed Any: " + ", ".join(sorted(LEAKS)), file=sys.stderr)
    ast.parse(stub)  # a syntax error here is a generator bug, never a silent bad stub
    init = (HEADER + '"""keta: bar-structure analysis kernel (C++), scriptable from Python."""\n\n'
            "from keta._keta import *  # noqa: F401,F403\n"
            "from keta._keta import __version__ as __version__\n")
    ast.parse(init)
    return {"_keta.pyi": stub, "__init__.pyi": init, "py.typed": ""}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--module", default=os.path.join(ROOT, "build", "python"),
                    help="directory holding the built keta package (default: build/python)")
    ap.add_argument("--check", action="store_true", help="exit 1 when the committed stubs differ")
    ap.add_argument("--out", default=OUT_DIR, help="output directory (default: python/keta)")
    a = ap.parse_args()
    files = generate(a.module)
    drift = []
    for fn, text in files.items():
        path = os.path.join(a.out, fn)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            drift.append(fn)
            if not a.check:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    if a.check:
        if drift:
            print("stale stubs: " + ", ".join(drift) + " — run: python3 tools/gen_pyi.py", file=sys.stderr)
            return 1
        print("stubs up to date")
        return 0
    print(("wrote " + ", ".join(drift)) if drift else "stubs already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
